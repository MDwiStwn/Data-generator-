<?php

namespace App\Services;

use App\Support\DataSanitizer;
use App\Support\TemplateSchema;
use Maatwebsite\Excel\Facades\Excel;
use App\Exports\TestDataExport;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Symfony\Component\HttpFoundation\StreamedResponse;

// Service untuk handle export file (CSV & Excel XLSX)
class ExportService
{
    // Fungsi export ke format CSV
    public function exportCsv(string $category, array $headers, array $keys, array $data): StreamedResponse
    {
        $prefix = match ($category) {
            'pegawai' => 'sample_import_pegawai',
            'murid' => 'format_dapodik_murid',
            'tagihan' => 'sample_import_tagihan',
            default => $category,
        };
        $filename = DataSanitizer::safeFilename($prefix, 'csv');

        return response()->streamDownload(function () use ($headers, $keys, $data) {
            $handle = fopen('php://output', 'w');

            // BOM for UTF-8 encoding in Excel
            fwrite($handle, "\xEF\xBB\xBF");

            // Write headers
            fputcsv($handle, $headers);

            // Write data rows with sanitization
            foreach ($data as $row) {
                $values = [];
                foreach ($keys as $key) {
                    $value = $row[$key] ?? '';
                    if ($value instanceof \DateTimeInterface) {
                        $value = $value->format('Y-m-d');
                    } elseif (is_array($value)) {
                        if (isset($value['date']) && is_string($value['date'])) {
                            $value = mb_substr($value['date'], 0, 10);
                        } else {
                            $value = implode(', ', array_filter($value, fn($v) => is_scalar($v)));
                        }
                    }
                    $values[] = (string) $value;
                }
                $sanitizedRow = DataSanitizer::sanitizeRow($values);
                fputcsv($handle, $sanitizedRow);
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }

    /**
     * Export data as Excel (XLSX) download.
     */
    public function exportExcel(string $category, array $headers, array $keys, array $data): BinaryFileResponse
    {
        $prefix = match ($category) {
            'pegawai' => 'sample_import_pegawai',
            'murid' => 'format_dapodik_murid',
            'tagihan' => 'sample_import_tagihan',
            default => $category,
        };
        $filename = DataSanitizer::safeFilename($prefix, 'xlsx');
        $sheetName = TemplateSchema::getSheetName($category);

        $export = new TestDataExport($headers, $keys, $data, $sheetName, $category);

        return Excel::download($export, $filename);
    }

    /**
     * Export data as SQL INSERT dump download.
     */
    public function exportSql(string $category, array $headers, array $keys, array $data): StreamedResponse
    {
        $table = match ($category) {
            'pegawai' => 'pegawai',
            'murid'   => 'peserta_didik',
            'tagihan' => 'tagihan_siswa',
            default   => str_starts_with($category, 'custom_') ? 'custom_data_' . substr($category, 7) : $category,
        };
        $filename = DataSanitizer::safeFilename($table, 'sql');

        return response()->streamDownload(function () use ($table, $keys, $data) {
            $handle = fopen('php://output', 'w');
            fwrite($handle, "-- Generated by DataGen Studio\n-- Table: `{$table}`\n\n");

            foreach (array_chunk($data, 50) as $chunk) {
                $columns = implode(', ', array_map(fn($k) => "`" . str_replace('`', '``', (string)$k) . "`", $keys));
                $valuesList = [];
                foreach ($chunk as $row) {
                    $escaped = array_map(function ($k) use ($row) {
                        $v = $row[$k] ?? null;
                        if ($v === null || $v === '') {
                            return 'NULL';
                        }
                        if (is_numeric($v) && !str_starts_with((string)$v, '0')) {
                            return (string) $v;
                        }
                        return "'" . addslashes((string) $v) . "'";
                    }, $keys);
                    $valuesList[] = '  (' . implode(', ', $escaped) . ')';
                }
                fwrite($handle, "INSERT INTO `{$table}` ({$columns}) VALUES\n" . implode(",\n", $valuesList) . ";\n\n");
            }

            fclose($handle);
        }, $filename, [
            'Content-Type' => 'application/sql; charset=UTF-8',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }
}
